static inline const unsigned char *cyrillic_glyph_rows(unsigned int cp) {
    switch (cp) {
        case 0x0410: return (const unsigned char *)font8x8_basic[(int)'A'];
        case 0x0412: return (const unsigned char *)font8x8_basic[(int)'B'];
        case 0x0415: return (const unsigned char *)font8x8_basic[(int)'E'];
        case 0x0406: return (const unsigned char *)font8x8_basic[(int)'I'];
        case 0x041A: return (const unsigned char *)font8x8_basic[(int)'K'];
        case 0x041C: return (const unsigned char *)font8x8_basic[(int)'M'];
        case 0x041D: return (const unsigned char *)font8x8_basic[(int)'H'];
        case 0x041E: return (const unsigned char *)font8x8_basic[(int)'O'];
        case 0x0420: return (const unsigned char *)font8x8_basic[(int)'P'];
        case 0x0421: return (const unsigned char *)font8x8_basic[(int)'C'];
        case 0x0422: return (const unsigned char *)font8x8_basic[(int)'T'];
        case 0x0423: return (const unsigned char *)font8x8_basic[(int)'Y'];
        case 0x0425: return (const unsigned char *)font8x8_basic[(int)'X'];
        default: break;
    }
    for (int i = 0; i < N_CYR_GLYPHS; i++) {
        if (font8x8_cyrillic[i].codepoint == cp) return font8x8_cyrillic[i].rows;
    }
    return NULL;
}

